def replay() -> dict:
    order = list(INITIAL_ORDER)
    action_log: list[dict] = []
    public_log: list[dict] = []
    turn, round_no, revision = 1, 1, 0
    for step in PLAN:
        entry = {
            "actor": step[1],
            "participant": step[1],
            "turn": turn,
            "round": round_no,
            "revision": revision,
            "order_before": list(order),
            "order_after": list(order),
        }
        if step[0] == "reject":
            entry.update({"accepted": False, "raw_action": step[2], "error": step[3]})
            action_log.append(entry)
        elif step[0] == "pass":
            entry.update({
                "op": "PASS",
                "accepted": True,
                "action": {"op": "PASS", "reason": step[4]},
                "reason": step[4],
            })
            action_log.append(entry)
        else:
            _, actor, item_id, position, reason = step
            from_position = order.index(item_id) + 1
            order.remove(item_id)
            order.insert(position - 1, item_id)
            revision += 1
            entry.update({
                "op": "MOVE",
                "accepted": True,
                "item_id": item_id,
                "from_position": from_position,
                "to_position": position,
                "original_position": from_position,
                "new_position": position,
                "reason": reason,
                "public_justification": reason,
                "revision": revision,
            })
            public_log.append(dict(entry))
            entry["action"] = {
                "op": "MOVE", "item_id": item_id, "position": position, "reason": reason,
            }
            action_log.append(entry)
        if turn % len(PLAYER_NAMES) == 0:
            round_no += 1
        turn += 1
    return {
        "order": list(order),
        "revision": revision,
        "round": round_no,
        "public_log": public_log,
        "turn": turn,
        "action_log": action_log,
        "initial_order": list(INITIAL_ORDER),
        "item_descriptions": ITEMS,
        "player_names": list(PLAYER_NAMES),
        "rounds": 2,
    }


